export function uniqueRuleIds() {
  return [...new Set(RULE_CATALOG.map((rule) => rule.ruleId))];
}

export function getRulesByCourseType(courseType) {
  return RULE_CATALOG.filter((rule) => rule.courseType === courseType);
}

export function getRulesByCategory(category) {
  return RULE_CATALOG.filter((rule) => rule.category === category);
}

export function getRulesByValidationType(validationType) {
  return RULE_CATALOG.filter((rule) => rule.validationType === validationType);
}
